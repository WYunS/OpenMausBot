import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {parse} from 'yaml';
import {releaseRepository} from '../.release/repository.mjs';
const {repository,owner,repo}=releaseRepository();
const resources=resolve(process.argv[2]);
const update=parse(readFileSync(join(resources,'app-update.yml'),'utf8'));
assert.equal(update.provider,'github');
assert.equal(update.owner,owner);
assert.equal(update.repo,repo);
assert.equal(update.token,undefined);
assert.equal(update.publisherName,undefined);
const meta=JSON.parse(readFileSync(join(resources,'enterprise-release.json'),'utf8'));
assert.equal(meta.version,JSON.parse(readFileSync('package.json','utf8')).version);
assert.equal(meta.repository,repository);
assert.equal(meta.sandboxPreset,'absent');
assert.equal(meta.humanAcceptance,'not-run');
assert(!existsSync(join(resources,'ruijie-sandbox')),'A repository-only release must not contain a sandbox preset');
for(const file of ['app.asar','ui/index.html','server/index.js','server/ruijie-computer-proxy.js','companion/index.js','licenses/OpenMausBot-LICENSE.txt','licenses/OpenMausBot-NOTICE.txt'])assert(existsSync(join(resources,file)),`Missing resource ${file}`);
console.log('Verified enterprise repository, version, packaged resources and absence of sandbox preset.');
